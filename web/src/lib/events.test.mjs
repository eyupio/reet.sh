import { readFileSync } from 'node:fs'
import { test } from 'node:test'
import assert from 'node:assert/strict'
import ts from 'typescript'
// Compile the pure label helper without a browser or an extra test dependency.
const compile = name => ts.transpileModule(readFileSync(new URL(name, import.meta.url), 'utf8'), { compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 } }).outputText
const asURL = source => `data:text/javascript;base64,${Buffer.from(source).toString('base64')}`
const launchURL = asURL(compile('./agentLaunch.ts').replace("from './catalogue'", `from '${asURL(compile('./catalogue.ts'))}'`))
const { eventLabel, eventCategory, eventRemedy } = await import(asURL(compile('./events.ts').replace("from './agentLaunch'", `from '${launchURL}'`)))
const event = (action, detail) => ({ id: 1, at: 0, source: 'ui', action, ...(detail ? { detail: JSON.stringify(detail) } : {}) })
test('ownership receipt events read as plain sentences from their metadata', () => {
  assert.equal(eventLabel(event('skill-content-adopt', { name: 'demo', files: 3, receiptId: 'a'.repeat(48) })), 'Recorded ownership of 3 files of demo')
  assert.equal(eventLabel(event('skill-content-release', { name: 'demo', receiptId: 'a'.repeat(48) })), 'Released ownership of demo')
})
test('one adopted file reads as "1 file", and a release without a name still reads', () => {
  assert.equal(eventLabel(event('skill-content-adopt', { name: 'demo', files: 1, receiptId: 'a'.repeat(48) })), 'Recorded ownership of 1 file of demo')
  assert.equal(eventLabel(event('skill-content-release', { receiptId: 'a'.repeat(48) })), 'Released ownership of a skill')
  assert.equal(eventLabel(event('skill-content-release')), 'Released ownership of a skill')
})
test('other activity labels are unchanged', () => {
  assert.equal(eventLabel(event('add', { name: 'demo' })), 'Added demo')
  assert.equal(eventLabel(event('merge-machines', { from: 'old', to: 'new' })), 'Consolidated machine old as new')
  assert.equal(eventLabel(event('frobnicate', { name: 'demo' })), 'frobnicate demo')
})
test('a terminal launch reads as which agent started where, never the prompt', () => {
  assert.equal(eventLabel(event('terminal-launch', { machine: 'agent-1', host: 'studio', tool: 'claude', model: '', dir: '/home/me/work/site' })), 'Started Claude Code in /home/me/work/site on studio')
  assert.equal(eventLabel(event('terminal-launch', { machine: 'agent-1', host: 'studio', tool: 'gemini', model: 'gemini-2.5-pro', dir: '' })), 'Started Gemini CLI with gemini-2.5-pro in the home folder on studio')
  assert.equal(eventLabel(event('terminal-launch')), 'Started an agent in the home folder on a machine')
})
test('project activity reads as plain sentences and never names a prompt', () => {
  assert.equal(eventLabel(event('project-create', { project: 'p1', name: 'Site', members: 3 })), 'Created project Site with 3 repositories')
  assert.equal(eventLabel(event('project-create', { project: 'p1', name: 'Site', members: 1 })), 'Created project Site with 1 repository')
  assert.equal(eventLabel(event('project-update', { project: 'p1', name: 'Site', members: 2 })), 'Updated project Site')
  assert.equal(eventLabel(event('project-update', { project: 'p1', name: 'Site', previousName: 'Web', members: 2 })), 'Renamed project Web to Site')
  assert.equal(eventLabel(event('project-delete', { project: 'p1', name: 'Site', members: 2 })), 'Deleted project Site')
  assert.equal(eventLabel(event('project-run', { project: 'p1', run: 'r1', members: 3 })), 'Started a Project run on 3 repositories')
  assert.equal(eventLabel(event('project-run', { project: 'p1', run: 'r1', members: 1 })), 'Started a Project run on 1 repository')
  assert.equal(eventLabel(event('project-run-retry', { project: 'p1', run: 'r1', position: 1, attempt: 2 })), 'Tried repository 2 of a Project run again (attempt 2)')
  assert.equal(eventLabel(event('project-run-retry')), 'Tried a repository of a Project run again')
  assert.equal(eventLabel(event('project-create')), 'Created a project')
  assert.equal(eventLabel(event('worktree-remove', { machine: 'a1', host: 'studio', path: '/home/me/.reet/worktrees/site/app/abc', branch: 'reet/site-abc' })), 'Removed a worktree on studio; the branch reet/site-abc is kept')
})
test('folder project activity reads as plain sentences and never names a prompt', () => {
  assert.equal(eventLabel(event('projects-migrated', { project: 'Shop', folderProjects: ['a', 'b'] })), 'Moved saved Project Shop into the rail as 2 projects')
  assert.equal(eventLabel(event('projects-migrated', { project: 'Shop', folderProjects: ['a'] })), 'Moved saved Project Shop into the rail as 1 project')
  assert.equal(eventLabel(event('projects-migrated', { project: 'Shop', folderProjects: [] })), 'Looked at saved Project Shop: none of its folders could become a project')
  assert.equal(eventLabel(event('projects-migrated')), 'Moved a saved Project into the rail')
  assert.equal(eventLabel(event('project-add', { project: 'p1', machine: 'a1', host: 'studio', folder: '/home/me/reet', name: 'reet' })), 'Added project reet (/home/me/reet on studio)')
  assert.equal(eventLabel(event('project-add', { project: 'p1', machine: 'a1', host: '', folder: '/home/me/reet', name: 'reet' })), 'Added project reet (/home/me/reet on a machine)')
  assert.equal(eventLabel(event('project-update', { project: 'p1', machine: 'a1', host: 'studio', folder: '/home/me/reet', name: 'reet' })), 'Updated project reet')
  assert.equal(eventLabel(event('project-remove', { project: 'p1', machine: 'a1', host: 'studio', folder: '/home/me/reet', name: 'reet' })), 'Removed project reet; its folder on studio is untouched')
  assert.equal(eventLabel(event('project-remove')), 'Removed a project')
  assert.equal(eventLabel(event('folder-browse', { machine: 'a1', path: '~', pages: 3 })), 'Browsed folders from ~ (3 pages)')
  assert.equal(eventLabel(event('folder-browse', { machine: 'a1', path: '/srv/site', pages: 1 })), 'Browsed folders from /srv/site (1 page)')
  assert.equal(eventLabel(event('folder-browse')), 'Browsed folders on a machine')
})
test('activity events fall into the areas the filters offer', () => {
  assert.equal(eventCategory(event('terminal-launch')), 'agents')
  assert.equal(eventCategory(event('worktree-remove')), 'agents')
  assert.equal(eventCategory(event('sync-agent-update')), 'agents')
  assert.equal(eventCategory(event('project-create')), 'projects')
  assert.equal(eventCategory(event('folder-browse')), 'projects')
  assert.equal(eventCategory(event('add')), 'skills')
  assert.equal(eventCategory(event('bulk-tag')), 'skills')
  assert.equal(eventCategory(event('hosted-save')), 'skills')
  assert.equal(eventCategory(event('list-update')), 'lists')
  assert.equal(eventCategory(event('sign-in')), 'account')
  assert.equal(eventCategory(event('mcp-rotate')), 'account')
  assert.equal(eventCategory(event('user-role')), 'account')
  assert.equal(eventCategory(event('settings')), 'admin')
  assert.equal(eventCategory(event('mail-check')), 'admin')
  assert.equal(eventCategory(event('ticket-reply')), 'admin')
  assert.equal(eventCategory(event('frobnicate')), 'account')
})
test('a failed mail check or test points at the settings that fix it, and nothing else grows a link', () => {
  assert.deepEqual(eventRemedy(event('mail-check', { ok: false, host: 'smtp.example' })), { label: 'Check the mail server settings', href: '/admin/email' })
  assert.deepEqual(eventRemedy(event('mail-test', { ok: false, to: 'a@example.com' })), { label: 'Check the mail server settings', href: '/admin/email' })
  assert.equal(eventRemedy(event('mail-check', { ok: true })), null)
  assert.equal(eventRemedy(event('project-create', { name: 'Site' })), null)
})
