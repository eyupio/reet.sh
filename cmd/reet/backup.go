func runBackup(args []string, out io.Writer) error {
	if len(args) > 0 && (args[0] == "--help" || args[0] == "-h" || args[0] == "help") {
		fmt.Fprintln(out, "Usage: reet backup keygen | list | run | open | escrow | unescrow | restore [--yes] ID\n\nlist reads local instance copies; run takes a sealed backup.\nopen decrypts a copy; restore requires its ID and confirmation.\nUse the existing REET_DATA_DIR and backup credentials for this instance.")
		return nil
	}
	if len(args) == 0 {
		return errors.New("usage: reet backup keygen | list | run | open | escrow | unescrow | restore [--yes] ID")
	}
	switch args[0] {
	case "keygen":
		key, err := backup.GenerateKey()
		if err != nil {
			return err
		}
		fmt.Fprintln(out, key)
		return nil
	case "list":
		return backupList(out)
	case "run":
		return backupRun(out)
	case "open":
		return backupOpen(args[1:], out)
	case "escrow":
		return backupEscrow(args[1:], out)
	case "unescrow":
		return backupUnescrow(args[1:], out)
	case "restore":
		return backupRestore(args[1:], out)
	default:
		return fmt.Errorf("unknown backup command %q; use keygen, list, run, open, escrow, unescrow or restore", args[0])
	}
}

func openBackup() (*store.Store, *backup.Service, error) {
	st, err := store.Open(env("REET_DATA_DIR", "./data"))
	if err != nil {
		return nil, nil, err
	}
	cfg, err := backup.FromEnv(os.Getenv)
	if err != nil {
		// A wrong environment value is reported, but a key that is merely
		// missing was generated by FromEnv and backups remain usable.
		fmt.Fprintf(os.Stderr, "backups: %v\n", err)
	}
	return st, backup.New(st, cfg), nil
}

func backupList(out io.Writer) error {
	st, svc, err := openBackup()
	if err != nil {
		return err
	}
	defer st.Close()
	items, err := svc.LocalItems(0)
	if err != nil {
		return err
	}
	if len(items) == 0 {
		fmt.Fprintln(out, "No instance backups are on this machine yet.")
		return nil
	}
	fmt.Fprintf(out, "%-40s %-20s %10s\n", "BACKUP", "TAKEN", "SIZE")
	for _, it := range items {
		fmt.Fprintf(out, "%-40s %-20s %10s\n", it.ID, time.UnixMilli(it.TakenAt).Local().Format("2006-01-02 15:04"), humanBytes(it.Bytes))
	}
	return nil
}

func backupRun(out io.Writer) error {
	st, svc, err := openBackup()
	if err != nil {
		return err
	}
	defer st.Close()
	item, err := svc.RunInstance(context.Background(), "cli")
	if err != nil {
		return err
	}
	fmt.Fprintf(out, "Took %s (%s).\n", item.ID, humanBytes(item.Bytes))
	if len(item.Remotes) == 0 {
		fmt.Fprintln(out, "It is on this machine; no destination confirmed a copy.")
	}
	return nil
}

// passwordFlags adds the two ways a password-protected copy takes its
// password. The file form accepts - for standard input.
func passwordFlags(f *flag.FlagSet) (file, literal *string) {
	return f.String("password-file", "", "read the copy password from this file, or - for standard input"),
		f.String("password", "", "the copy password, for a copy protected with one")
}

func passphraseFlags(f *flag.FlagSet) (file, literal *string) {
	return f.String("passphrase-file", "", "read the escrow passphrase from this file, or - for standard input"),
		f.String("passphrase", "", "the escrow passphrase")
}

func readPassword(file, literal string) (string, error) {
	if file != "" && literal != "" {
		return "", errors.New("give either --password or --password-file, not both")
	}
	if literal != "" {
		return literal, nil
	}
	if file == "" {
		return "", nil
	}
	var raw []byte
	var err error
	if file == "-" {
		raw, err = io.ReadAll(os.Stdin)
	} else {
		raw, err = os.ReadFile(file)
	}
	if err != nil {
		return "", fmt.Errorf("reading the copy password: %w", err)
	}
	return strings.TrimSpace(string(raw)), nil
}

func backupOpen(args []string, out io.Writer) error {
	f := flag.NewFlagSet("reet backup open", flag.ContinueOnError)
	f.SetOutput(out)
	file, literal := passwordFlags(f)
	if err := f.Parse(args); err != nil {
		return err
	}
	if f.NArg() > 1 {
		return errors.New("expected one backup FILE")
	}
	path, err := clientconfig.Require(f.Arg(0), "backup FILE", false, os.Stdin, os.Stderr)
	if err != nil {
		return err
	}
	raw, err := os.ReadFile(path)
	if err != nil {
		return err
	}
	password, err := readPassword(*file, *literal)
	if err != nil {
		return err
	}
	key := ""
	if m, err := backup.ManifestOf(raw); err != nil {
		return err
	} else if m.Protection == backup.ProtectionPassword && password == "" {
		password, err = clientconfig.Require("", "copy password (--password-file)", true, os.Stdin, os.Stderr)
		if err != nil {
			return err
		}
	} else if m.Protection != backup.ProtectionPassword {
		key, err = backup.Lookup(os.Getenv, backup.EnvKey)
		if err != nil {
			return err
		}
		key, err = clientconfig.Require(key, "REET_BACKUP_KEY", true, os.Stdin, os.Stderr)
		if err != nil {
			return err
		}
	}
	_, payload, err := backup.OpenArchive(raw, password, key)
	if err != nil {
		return err
	}
	_, err = out.Write(payload)
	return err
}

func backupEscrow(args []string, out io.Writer) error {
	f := flag.NewFlagSet("reet backup escrow", flag.ContinueOnError)
	f.SetOutput(out)
	outPath := f.String("out", "", "write the sealed escrow here")
	file, literal := passphraseFlags(f)
	if err := f.Parse(args); err != nil {
		return err
	}
	path, inputErr := clientconfig.Require(*outPath, "--out (escrow output file)", false, os.Stdin, os.Stderr)
	if inputErr != nil {
		return inputErr
	}
	*outPath = path
	passphrase, err := readPassword(*file, *literal)
	if err != nil {
		return err
	}
	passphrase, err = clientconfig.Require(passphrase, "escrow passphrase (--passphrase-file)", true, os.Stdin, os.Stderr)
	if err != nil {
		return err
	}
	if len(passphrase) < backup.MinPassword {
		return fmt.Errorf("the escrow passphrase needs at least %d characters", backup.MinPassword)
	}
	st, svc, err := openBackup()
	if err != nil {
		return err
	}
	defer st.Close()
	e, err := svc.Escrow(0)
	if err != nil {
		return err
	}
	sealed, err := backup.SealEscrow(e, passphrase)
	if err != nil {
		return err
	}
	if err := os.WriteFile(*outPath, sealed, 0o600); err != nil {
		return err
	}
	fmt.Fprintf(out, "Escrow written to %s with %d destination(s). Keep it and the passphrase somewhere other than this machine and the backup bucket.\n", *outPath, len(e.Destinations))
	return nil
}

func backupUnescrow(args []string, out io.Writer) error {
	f := flag.NewFlagSet("reet backup unescrow", flag.ContinueOnError)
	f.SetOutput(out)
	inPath := f.String("in", "", "read the sealed escrow from here")
	name := f.String("remote", "", "the destination to print; the first when empty")
	file, literal := passphraseFlags(f)
	if err := f.Parse(args); err != nil {
		return err
	}
	path, inputErr := clientconfig.Require(*inPath, "--in (escrow input file)", false, os.Stdin, os.Stderr)
	if inputErr != nil {
		return inputErr
	}
	*inPath = path
	passphrase, err := readPassword(*file, *literal)
	if err != nil {
		return err
	}
	passphrase, err = clientconfig.Require(passphrase, "escrow passphrase (--passphrase-file)", true, os.Stdin, os.Stderr)
	if err != nil {
		return err
	}
	raw, err := os.ReadFile(*inPath)
	if err != nil {
		return err
	}
	e, err := backup.OpenEscrow(raw, passphrase)
	if err != nil {
		return err
	}
	fmt.Fprintf(out, "REET_BACKUP_KEY=%s\n", e.Key)
	var chosen *backup.EscrowRemote
	var others []string
	for i := range e.Destinations {
		r := &e.Destinations[i]
		if (*name == "" && chosen == nil) || r.Name == *name {
			chosen = r
		} else {
			others = append(others, r.Name)
		}
	}
	if chosen == nil {
		if len(e.Destinations) == 0 {
			return errors.New("this escrow holds no destinations")
		}
		return fmt.Errorf("this escrow holds no destination named %q; it holds %s", *name, strings.Join(others, ", "))
	}
	fmt.Fprintf(out, "REET_BACKUP_S3_NAME=%s\n", chosen.Name)
	fmt.Fprintf(out, "REET_BACKUP_S3_ENDPOINT=%s\n", chosen.Endpoint)
	fmt.Fprintf(out, "REET_BACKUP_S3_REGION=%s\n", chosen.Region)
	fmt.Fprintf(out, "REET_BACKUP_S3_BUCKET=%s\n", chosen.Bucket)
	fmt.Fprintf(out, "REET_BACKUP_S3_PREFIX=%s\n", chosen.Prefix)
	fmt.Fprintf(out, "REET_BACKUP_S3_ACCESS_KEY_ID=%s\n", chosen.AccessKey)
	fmt.Fprintf(out, "REET_BACKUP_S3_SECRET_ACCESS_KEY=%s\n", chosen.SecretKey)
	if chosen.Passphrase != "" {
		fmt.Fprintf(out, "REET_BACKUP_S3_PASSPHRASE=%s\n", chosen.Passphrase)
	}
	if chosen.PathStyle != nil {
		fmt.Fprintf(out, "REET_BACKUP_S3_PATH_STYLE=%t\n", *chosen.PathStyle)
	}
	if len(others) > 0 {
		fmt.Fprintf(out, "# other destinations: %s\n", strings.Join(others, ", "))
	}
	return nil
}

func backupRestore(args []string, out io.Writer) error {
	f := flag.NewFlagSet("reet backup restore", flag.ContinueOnError)
	f.SetOutput(out)
	yes := f.Bool("yes", false, "confirm replacing the live database")
	file, literal := passwordFlags(f)
	if err := f.Parse(args); err != nil {
		return err
	}
	if f.NArg() > 1 {
		return errors.New("expected one backup ID")
	}
	id, inputErr := clientconfig.Require(f.Arg(0), "backup ID", false, os.Stdin, os.Stderr)
	if inputErr != nil {
		return inputErr
	}
	if !*yes {
		return errors.New("this replaces the live database; stop reet first, then run again with --yes")
	}
	data := env("REET_DATA_DIR", "./data")
	st, svc, err := openBackup()
	if err != nil {
		return err
	}
	password, err := readPassword(*file, *literal)
	if err != nil {
		st.Close()
		return err
	}
	result, err := backup.RestoreInstance(context.Background(), svc, data, id, password, st.Close)
	if errors.Is(err, backup.ErrPasswordRequired) && password == "" {
		password, err = clientconfig.Require("", "copy password (--password-file)", true, os.Stdin, os.Stderr)
		if err == nil {
			result, err = backup.RestoreInstance(context.Background(), svc, data, id, password, st.Close)
		}
	}
	if err != nil {
		return err
	}
	fmt.Fprint(out, result.Message)
	return nil

}

func humanBytes(n int64) string {
	const unit = 1024
	if n < unit {
		return fmt.Sprintf("%d B", n)
	}
	div, exp := int64(unit), 0
	for n/div >= unit {
		div *= unit
		exp++
	}
	return fmt.Sprintf("%.1f %cB", float64(n)/float64(div), "KMGTPE"[exp])
}
