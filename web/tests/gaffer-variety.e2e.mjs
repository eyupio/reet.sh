// Foreground performances rotate independently of tool updates and yield to real status.
import { chromium, expect } from '@playwright/test'
import { startHarness } from './helpers/harness.mjs'

const harness = await startHarness()
const browser = await chromium.launch({ headless: true, executablePath: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH || '/usr/bin/chromium', args: ['--no-sandbox'] })
try {
  const page = await browser.newPage({ viewport: { width: 1280, height: 1000 } })
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.addInitScript(() => { Math.random = () => .01 })
  await page.goto(`${harness.url}/tests/fixtures/gaffer-progress.html`)
  const card = page.getByRole('region', { name: 'Gaffer’s work update' })
  await expect(card).toHaveAttribute('data-phase', 'editing')
  const avatar = card.locator('.gaffer-avatar')
  await page.clock.install()
  await page.clock.fastForward(14_000)
  await expect(avatar).toHaveAttribute('data-reaction', 'look-around')
  const frames = await avatar.locator('.scene:not(.leaving) .frames').elementHandle()
  await page.evaluate(() => window.__gaffer.emit({ seq: 1000, kind: 'tool', toolCallId: 'next-read', toolKind: 'read', path: '/project/page.ts', status: 'in_progress' }))
  await expect(card).toHaveAttribute('data-phase', 'reading')
  await expect(avatar).toHaveAttribute('data-reaction', 'look-around')
  expect(await frames.evaluate(node => node.isConnected)).toBe(true)
  await page.clock.fastForward(4_300)
  await page.clock.fastForward(13_000)
  await expect(avatar).toHaveAttribute('data-artwork', 'tea')
  // Completing a turn changes the facts immediately, while the supervisor finishes his brew.
  await page.evaluate(() => {
    window.__gaffer.emit({ seq: 1001, kind: 'tool', toolCallId: 'next-read', toolKind: 'read', status: 'completed' })
    window.__gaffer.emit({ seq: 1002, kind: 'tool', toolCallId: 'edit', toolKind: 'edit', status: 'completed' })
    window.__gaffer.emit({ seq: 1003, kind: 'agent', messageId: 'handover', text: 'The change is ready to review.' })
    window.__gaffer.emit({ seq: 1004, kind: 'status', state: 'idle' })
  })
  await expect(card).toHaveAttribute('data-phase', 'idle')
  await expect(avatar).toHaveAttribute('data-artwork', 'tea')
  await page.clock.fastForward(4_000)
  await page.clock.fastForward(13_000)
  await expect(avatar).toHaveAttribute('data-reaction', 'rest-head')
  await page.evaluate(() => {
    window.__gaffer.emit({ seq: 1005, kind: 'user', text: 'Check the next change.' })
    window.__gaffer.emit({ seq: 1006, kind: 'status', state: 'working' })
    window.__gaffer.emit({ seq: 1007, kind: 'tool', toolCallId: 'next-edit', toolKind: 'edit', path: '/project/next.ts', status: 'in_progress' })
  })
  await expect(card).toHaveAttribute('data-phase', 'editing')
  await expect(avatar).not.toHaveAttribute('data-reaction', 'rest-head')
  await page.clock.fastForward(13_000)
  await expect(avatar).toHaveAttribute('data-reaction', 'scratch-head')
  await page.getByRole('button', { name: 'Approval', exact: true }).click()
  await page.clock.fastForward(100)
  await expect(card).toHaveAttribute('data-phase', 'approval')
  await expect(avatar.locator('.frames')).toHaveCount(0)
  await expect(avatar.locator('.question')).toHaveCount(1)
  await page.getByRole('button', { name: 'Editing', exact: true }).click()
  await page.clock.fastForward(100)
  await expect(card).toHaveAttribute('data-phase', 'editing')
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.clock.fastForward(35_000)
  await expect(avatar).toHaveAttribute('data-reaction', '')
  expect(await avatar.evaluate(node => node.getAnimations({ subtree: true }).length)).toBe(0)
  expect(errors).toEqual([])
  console.log('Gaffer variety: foreground rotation, a brew without leaving, uninterrupted tool updates, idle rest, immediate wake and approval, reduced motion.')
} finally { await browser.close(); await harness.close() }
