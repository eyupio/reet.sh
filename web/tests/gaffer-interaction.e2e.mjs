import { chromium, expect } from '@playwright/test'
import { startHarness } from './helpers/harness.mjs'

const harness = await startHarness()
const browser = await chromium.launch({ headless: true, executablePath: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH || '/usr/bin/chromium', args: ['--no-sandbox'] })
const errors = []
try {
  const page = await browser.newPage({ viewport: { width: 1280, height: 950 } })
  page.on('pageerror', error => errors.push(error.message))
  await page.clock.install()
  await page.goto(`${harness.url}/tests/fixtures/gaffer-progress.html`)
  const panel = page.getByRole('region', { name: 'Gaffer’s work update' })
  const avatar = panel.locator('.gaffer-avatar')
  const nudge = panel.getByRole('button', { name: 'Say ey up to Gaffer' })
  await expect(panel).toHaveAttribute('data-phase', 'editing')
  await page.clock.fastForward(4_000)
  await page.evaluate(() => {
    window.__nudgeActions = []
    document.addEventListener('gaffer-fixture-action', event => window.__nudgeActions.push(event.detail.kind))
  })
  // A nudge is answered by the scene he is already in: he flinches, nods or glances on top of it. Nothing is swapped.
  const reactionBefore = await avatar.getAttribute('data-reaction'), artworkBefore = await avatar.getAttribute('data-artwork')
  const performance = await avatar.locator('.scene:not(.leaving)').elementHandle()
  // The newest acknowledgement still playing (0 when none); a nudge answers over the tail of the last one, as a body would.
  const pokes = () => avatar.locator('.poke').evaluate(el => el.getAnimations().at(-1)?.effect.getTiming().duration ?? 0)
  await nudge.click()
  await expect(panel).toHaveAttribute('data-poke-count', '1')
  expect(await pokes()).toBe(620)
  await expect(avatar).toHaveAttribute('data-reaction', reactionBefore)
  await expect(avatar).toHaveAttribute('data-artwork', artworkBefore)
  const first = await panel.locator('.quote').textContent()
  await nudge.click()
  await expect(panel).toHaveAttribute('data-poke-count', '1')
  await page.clock.fastForward(700)
  await nudge.focus(); await page.keyboard.press('Enter')
  await expect(panel).toHaveAttribute('data-poke-count', '2')
  await expect.poll(pokes).toBe(820)
  await expect(panel.locator('.quote')).not.toHaveText(first)
  await expect(panel.locator('.quote')).toHaveAttribute('aria-live', 'polite')
  await page.clock.fastForward(700)
  await nudge.click()
  await expect(panel).toHaveAttribute('data-poke-count', '3')
  await expect.poll(pokes).toBe(860)
  // The same performance element is still there, still the same artwork and reaction: the body answered, the scene did not change.
  expect(await performance.evaluate(el => el.isConnected)).toBe(true)
  await expect(avatar).toHaveAttribute('data-artwork', artworkBefore)
  await expect.poll(pokes).toBe(0)
  await page.clock.fastForward(8_000)
  await expect(avatar).toHaveAttribute('data-reaction', '')
  await page.clock.fastForward(21_000)
  await nudge.click()
  await expect(panel).toHaveAttribute('data-poke-count', '1')

  await page.clock.fastForward(700); await nudge.click()
  await page.getByRole('button', { name: 'Error', exact: true }).click()
  await expect(avatar).toHaveAttribute('data-pose', 'concerned')
  await page.clock.fastForward(7_000)
  await expect(avatar).toHaveAttribute('data-pose', 'concerned')
  await expect(avatar.locator('.frames')).toHaveCount(0)
  await page.getByRole('button', { name: 'Approval', exact: true }).click()
  await page.clock.fastForward(700); await nudge.click()
  await expect(avatar).toHaveAttribute('data-pose', 'attention')
  await expect(avatar.locator('.frames')).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Allow once', exact: true })).toBeVisible()
  expect(await page.evaluate(() => window.__nudgeActions)).toEqual([])

  await page.getByRole('button', { name: 'Editing', exact: true }).click()
  await panel.getByRole('button', { name: 'Pause Gaffer animation' }).click()
  await page.clock.fastForward(700); await nudge.click()
  await expect(panel.locator('.quote')).toContainText('OpenCode')
  expect(await avatar.evaluate(el => el.getAnimations({ subtree: true }).length)).toBe(0)
  await page.clock.fastForward(13_000)
  await expect(panel.locator('.quote')).toHaveAttribute('aria-live', 'off')
  await page.getByRole('button', { name: 'Finished', exact: true }).click()
  const handover = await panel.locator('.handover').textContent()
  await page.clock.fastForward(700); await nudge.click()
  await expect(panel.locator('.click-aside')).toContainText('OpenCode')
  await expect(panel.locator('.handover')).toHaveText(handover)

  for (const theme of ['light', 'dark']) {
    const phone = await browser.newPage({ viewport: { width: 390, height: 900 }, reducedMotion: 'reduce', hasTouch: true })
    phone.on('pageerror', error => errors.push(error.message))
    await phone.clock.install()
    await phone.goto(`${harness.url}/tests/fixtures/gaffer-progress.html?theme=${theme}`)
    const card = phone.getByRole('region', { name: 'Gaffer’s work update' })
    await expect(card).toHaveAttribute('data-phase', 'editing')
    const button = card.getByRole('button', { name: 'Say ey up to Gaffer' })
    await button.tap()
    await phone.clock.fastForward(700); await button.tap()
    await expect(card).toHaveAttribute('data-poke-count', '2')
    await expect(card.locator('.quote')).toHaveAttribute('aria-live', 'polite')
    expect(await card.locator('.gaffer-avatar').evaluate(el => el.getAnimations({ subtree: true }).length)).toBe(0)
    expect(await phone.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await phone.close()
  }
  expect(errors).toEqual([])
  console.log('Gaffer interaction: deliberate nudges, keyboard/touch, bounded reply queue, unbroken gestures, streak reset, status priority, no agent actions, summary replies and reduced motion in both phone themes passed.')
} finally {
  await browser.close()
  await harness.close()
}
