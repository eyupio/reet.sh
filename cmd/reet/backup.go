package main

import (
	"context"
	"errors"
	"flag"
	"fmt"
	"io"
	"os"
	"path/filepath"
	"time"

	"github.com/eyupio/reet.sh/internal/backup"
	"github.com/eyupio/reet.sh/internal/store"
)

func runBackup(args []string, out io.Writer) error {
	if len(args) == 0 {
		return errors.New("usage: reet backup keygen | list | run | restore [--yes] ID")
	}
	switch args[0] {
	case "keygen":
		key, err := backup.GenerateKey()
		if err != nil {
			return err
		}
		fmt.Fprintln(out, key)
		return nil
	case "list":
		return backupList(out)
	case "run":
		return backupRun(out)
	case "restore":
		return backupRestore(args[1:], out)
	default:
		return fmt.Errorf("unknown backup command %q; use keygen, list, run or restore", args[0])
	}
}

func openBackup() (*store.Store, *backup.Service, error) {
	st, err := store.Open(env("REET_DATA_DIR", "./data"))
	if err != nil {
		return nil, nil, err
	}
	cfg, err := backup.FromEnv(os.Getenv)
	if err != nil {
		// A wrong environment value is reported, but a key that is merely
		// missing was generated by FromEnv and backups remain usable.
		fmt.Fprintf(os.Stderr, "backups: %v\n", err)
	}
	return st, backup.New(st, cfg), nil
}

func backupList(out io.Writer) error {
	st, svc, err := openBackup()
	if err != nil {
		return err
	}
	defer st.Close()
	items, err := svc.LocalItems(0)
	if err != nil {
		return err
	}
	if len(items) == 0 {
		fmt.Fprintln(out, "No instance backups are on this machine yet.")
		return nil
	}
	fmt.Fprintf(out, "%-40s %-20s %10s\n", "BACKUP", "TAKEN", "SIZE")
	for _, it := range items {
		fmt.Fprintf(out, "%-40s %-20s %10s\n", it.ID, time.UnixMilli(it.TakenAt).Local().Format("2006-01-02 15:04"), humanBytes(it.Bytes))
	}
	return nil
}

func backupRun(out io.Writer) error {
	st, svc, err := openBackup()
	if err != nil {
		return err
	}
	defer st.Close()
	item, err := svc.RunInstance(context.Background(), "cli")
	if err != nil {
		return err
	}
	fmt.Fprintf(out, "Took %s (%s).\n", item.ID, humanBytes(item.Bytes))
	if len(item.Remotes) == 0 {
		fmt.Fprintln(out, "It is on this machine; no destination confirmed a copy.")
	}
	return nil
}

func backupRestore(args []string, out io.Writer) error {
	f := flag.NewFlagSet("reet backup restore", flag.ContinueOnError)
	f.SetOutput(out)
	yes := f.Bool("yes", false, "confirm replacing the live database")
	if err := f.Parse(args); err != nil {
		return err
	}
	if f.NArg() != 1 {
		return errors.New("usage: reet backup restore --yes ID")
	}
	id := f.Arg(0)
	if !*yes {
		return errors.New("this replaces the live database; stop reet first, then run again with --yes")
	}
	data := env("REET_DATA_DIR", "./data")
	st, svc, err := openBackup()
	if err != nil {
		return err
	}
	m, payload, err := svc.Download(context.Background(), 0, id)
	if err != nil {
		st.Close()
		return err
	}
	st.Close()
	if m.Kind != "instance" {
		return errors.New("that is not an instance backup")
	}
	temp, err := os.CreateTemp(data, ".reet-restore-*.db")
	if err != nil {
		return err
	}
	tempName := temp.Name()
	temp.Close()
	defer os.Remove(tempName)
	if err := os.WriteFile(tempName, payload, 0o600); err != nil {
		return err
	}
	ctx, cancel := context.WithTimeout(context.Background(), time.Minute)
	defer cancel()
	if err := store.CheckDatabaseFile(ctx, tempName); err != nil {
		return fmt.Errorf("the backup does not pass an integrity check: %w", err)
	}
	live := filepath.Join(data, "reet.db")
	if _, err := os.Stat(live); err == nil {
		aside := live + ".before-restore-" + time.Now().UTC().Format("20060102T150405Z")
		if err := os.Rename(live, aside); err != nil {
			return err
		}
		fmt.Fprintf(out, "The database that was live is now %s.\n", aside)
	}
	for _, suffix := range []string{"-wal", "-shm"} {
		_ = os.Remove(live + suffix)
	}
	if err := os.Rename(tempName, live); err != nil {
		return err
	}
	if err := os.Chmod(live, 0o600); err != nil {
		return err
	}
	fmt.Fprintf(out, "Restored %s. Start reet again; it will open the restored database.\n", id)
	return nil
}

func humanBytes(n int64) string {
	const unit = 1024
	if n < unit {
		return fmt.Sprintf("%d B", n)
	}
	div, exp := int64(unit), 0
	for n/div >= unit {
		div *= unit
		exp++
	}
	return fmt.Sprintf("%.1f %cB", float64(n)/float64(div), "KMGTPE"[exp])
}
