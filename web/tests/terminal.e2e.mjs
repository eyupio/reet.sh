import { chromium, expect } from '@playwright/test'
import { mkdir } from 'node:fs/promises'

const base = process.env.REET_BROWSER_URL
if (!base || !process.env.REET_BROWSER_COOKIE) throw new Error('Run through the real Go terminal integration fixture')
const browser = await chromium.launch({ headless: true, executablePath: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH || undefined, args: ['--no-sandbox'] })
const context = await browser.newContext({ viewport: { width: 1360, height: 1000 } })
await context.addCookies([{ name: 'reet_session', value: process.env.REET_BROWSER_COOKIE, url: base, httpOnly: true, sameSite: 'Lax' }])
const page = await context.newPage()
const errors = []
let sockets = 0
let lastSize
page.on('websocket', socket => {sockets++;socket.on('framesent',({payload})=>{try{const message=JSON.parse(String(payload));if(message.type==='resize')lastSize={cols:message.cols,rows:message.rows}}catch{/* binary input */}})})
page.on('pageerror', error => errors.push(error.message))
const pane = page.getByRole('region', { name: 'Terminal on laptop' })
const screen = page.locator('.xterm-accessibility-tree')
async function live() { await expect(pane).toHaveAttribute('data-connection-state', 'live', { timeout: 20000 }) }
async function command(text) { await page.getByRole('button', { name: 'Focus terminal' }).click(); await page.keyboard.type(text); await page.keyboard.press('Enter') }
async function state() { return page.evaluate(async () => (await fetch('/_test/state')).json()) }

try {
  await page.goto(`${base}/machines?view=terminal&agent=${encodeURIComponent(process.env.REET_BROWSER_AGENT)}`)
  await expect(page.getByRole('heading', { name: 'Your machine. Your shell.' })).toBeVisible()
  await expect(page.getByRole('button', { name: 'New terminal' })).toBeEnabled()
  await page.getByLabel('New session name').fill('Browser durability')
  await page.getByRole('button', { name: 'New terminal', exact: true }).click()
  await live()
  await expect(screen).toContainText('stage6-ready>')
  await expect(page.getByLabel('Machine health')).toContainText('42.0')
  await command("sleep 300 & LONG_PID=$!; printf '__browser_%s__ %s\\n' 'started' \"$LONG_PID\"")
  await expect(screen).toContainText('__browser_started__')
  const original = await state()
  expect(original.sessions).toBe(1)
  expect(Number(original.pid)).toBeGreaterThan(0)
  await page.reload()
  await live()
  await command("kill -0 \"$LONG_PID\" && printf '__browser_%s__\\n' 'resumed'")
  await expect(screen).toContainText('__browser_resumed__')
  expect(await state()).toEqual(original)
  const beforeRestart = sockets
  await page.evaluate(async () => { const response = await fetch('/_test/restart-agent', { method: 'POST' }); if (!response.ok) throw new Error('test agent restart failed') })
  await expect.poll(() => sockets, { timeout: 20000 }).toBeGreaterThan(beforeRestart)
  await live()
  await command("kill -0 \"$LONG_PID\" && printf '__browser_%s__\\n' 'agent-survived'")
  await expect(screen).toContainText('__browser_agent-survived__')
  expect(await state()).toEqual(original)
  await command("printf '\\360\\237\\222\\245 __split_%s__\\n' 'utf8'")
  await expect(screen).toContainText('💥 __split_utf8__')
  const beforeController = sockets
  await page.evaluate(async()=>{const response=await fetch('/_test/restart-controller',{method:'POST'});if(!response.ok)throw new Error('controller restart failed')})
  await expect.poll(()=>sockets,{timeout:20000}).toBeGreaterThan(beforeController)
  await live()
  await command("kill -0 \"$LONG_PID\" && printf '__controller_%s__\\n' 'survived'")
  await expect(screen).toContainText('__controller_survived__')
  expect(await state()).toEqual(original)
  await command("printf '\\033[?1049h\\033[2J\\033[H__alternate_screen__\\n'")
  await expect(screen).toContainText('__alternate_screen__')
  await page.reload();await live()
  await expect(screen).toContainText('__alternate_screen__')
  await command("printf '\\033[?1049l'")
  await expect(screen).toContainText('__controller_survived__')
  await page.getByRole('button',{name:'Rename',exact:true}).click()
  await page.getByRole('dialog').getByLabel('Session name').fill('Build workspace')
  await page.getByRole('button',{name:'Save name',exact:true}).click()
  await expect(pane).toContainText('Build workspace')
  await page.getByRole('button',{name:'End session',exact:true}).click()
  await page.getByRole('dialog').getByRole('button',{name:'Cancel',exact:true}).click()
  await live()
  expect(await state()).toEqual(original)
  await page.getByRole('button',{name:'Search',exact:true}).click()
  await page.getByLabel('Find in terminal').fill('__split_utf8__')
  await page.getByRole('button',{name:'Next match',exact:true}).click()
  await expect(page.getByText('No matches',{exact:true})).toHaveCount(0)
  await page.getByRole('button',{name:'Close search',exact:true}).click()
  await page.locator('.screen').evaluate(element=>{const data=new DataTransfer();data.setData('text/plain',"printf '__must_not_execute__'\n");element.dispatchEvent(new ClipboardEvent('paste',{clipboardData:data,bubbles:true,cancelable:true}))})
  await expect(page.getByRole('dialog')).toContainText('Paste into the remote shell?')
  await page.getByRole('dialog').getByRole('button',{name:'Cancel',exact:true}).click()
  await command("printf '__safe_%s__\\n' 'after-cancel'")
  await expect(screen).toContainText('__safe_after-cancel__')
  await expect(screen).not.toContainText('__must_not_execute__')
  await page.getByRole('button',{name:'Recent history',exact:true}).click()
  await expect(page.getByRole('dialog')).toContainText('__browser_agent-survived__')
  await page.getByRole('button',{name:'Close history',exact:true}).click()
  await page.getByRole('button',{name:'Increase terminal font'}).click()
  await expect(page.getByLabel('Terminal font size')).toHaveText('15')
  await page.getByRole('button',{name:'Maximise',exact:true}).click()
  await expect(pane).toHaveClass(/maximised/)
  await expect.poll(()=>lastSize?.rows||0).toBeGreaterThan(35)
  const size={...lastSize}
  await command("set -- $(stty size); printf '__pty_size_%s_%s__\\n' \"$1\" \"$2\"")
  await expect(screen).toContainText(`__pty_size_${size.rows}_${size.cols}__`)
  await page.getByRole('button',{name:'Restore size',exact:true}).click()
  await page.setViewportSize({width:390,height:844})
  await page.evaluate(()=>document.documentElement.dataset.theme='dark')
  await expect(page.getByRole('button',{name:'Send Ctrl+C'})).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  if (process.env.REET_BROWSER_ARTIFACT_DIR) await page.screenshot({path:`${process.env.REET_BROWSER_ARTIFACT_DIR}/terminal-mobile-dark.png`,fullPage:true})
  await page.setViewportSize({width:1360,height:1000})
  await page.evaluate(()=>document.documentElement.dataset.theme='light')
  const storage=await page.evaluate(()=>JSON.stringify({local:{...localStorage},session:{...sessionStorage}}))
  expect(storage).not.toMatch(/__browser_|__controller_|LONG_PID|__split_utf8__/)
  await page.evaluate(async()=>{const response=await fetch('/_test/disable-terminals',{method:'POST'});if(!response.ok)throw new Error('rollback failed')})
  await page.reload()
  await expect(page.getByText(/Remote terminals are disabled on this server/)).toBeVisible()
  await expect(page.getByRole('button',{name:'New terminal',exact:true})).toBeDisabled()
  expect(await state()).toEqual(original)
  await page.evaluate(async()=>{const response=await fetch('/_test/enable-terminals',{method:'POST'});if(!response.ok)throw new Error('reenable failed')})
  await page.reload();await live()
  await command("kill -0 \"$LONG_PID\" && printf '__rollback_%s__\\n' 'survived'")
  await expect(screen).toContainText('__rollback_survived__')
  expect(await state()).toEqual(original)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  expect(errors).toEqual([])
  if (process.env.REET_BROWSER_ARTIFACT_DIR) { await mkdir(process.env.REET_BROWSER_ARTIFACT_DIR, { recursive: true }); await page.screenshot({ path: `${process.env.REET_BROWSER_ARTIFACT_DIR}/terminal-desktop.png`, fullPage: true }) }
  console.log(`Browser terminal passed: original shell PID ${original.pid}, one logical session, long job preserved through browser refresh and agent reconnect.`)
} finally { await browser.close() }
